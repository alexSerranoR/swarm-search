"""Build the results tables and figures from results/*.json.

Usage:
    python analysis/make_report.py

Writes:
    docs/results.md                       tables with paired bootstrap confidence intervals
    docs/figures/quality_vs_cost.png      NDCG@10 vs. cost per query, both datasets
    docs/figures/ndcg_ci.png              NDCG@10 per method with 95% bootstrap CIs
    docs/figures/coordination.png         duplicate-query rate and messages per query

All comparisons are PAIRED: methods are compared on exactly the same queries.
"""
import json
import random
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
DOCS = ROOT / "docs"
FIGS = DOCS / "figures"

# Claude Haiku 5.5 list prices (USD per million tokens, prompts <= 100k tokens)
PRICE_IN, PRICE_OUT = 0.10, 0.50
BOOTSTRAP = 10_000
SEED = 0

LABELS = {
    "bm25": "BM25",
    "agent": "Single agent",
    "rrf_n": "3 agents + RRF",
    "swarm": "Swarm (3)",
    "swarm6": "Swarm (6)",
}

EXPERIMENTS = {
    "fiqa": {
        "title": "FiQA-2018 (finance Q&A, 57,638 docs)",
        "files": {
            "bm25": "fiqa_bm25_n100.json",
            "agent": "fiqa_agent_n100.json",
            "rrf_n": "fiqa_rrf_n_n100.json",
            "swarm": "fiqa_swarm_n100.json",
            "swarm6": "fiqa_swarm6_n100.json",
        },
    },
    "scifact": {
        "title": "SciFact (scientific claims, 5,183 docs)",
        "files": {
            "bm25": "scifact_bm25_n50.json",
            "agent": "scifact_agent_n50.json",
            "rrf_n": "scifact_rrf_n_n30.json",
            "swarm": "scifact_swarm_n30.json",
        },
    },
}

COMPARISONS = [
    ("agent", "bm25"),
    ("rrf_n", "agent"),
    ("swarm", "rrf_n"),
    ("swarm", "agent"),
    ("swarm6", "swarm"),
    ("swarm", "bm25"),
]

# Chart styling: ASR brand (dark surface, lime accent). The swarm is the accent;
# every other method is neutral gray context. Identity is always carried by direct
# labels too, never by color alone.
SURFACE = "#0b0f14"   # brand background
INK = "#e8edf2"       # brand off-white
INK_2 = "#9aa3ab"
MUTED = "#3a424b"
GRID = "#1c222a"
ACCENT = "#b6f24a"    # brand lime -> swarm
NEUTRAL = "#6b737c"   # everything else
ON_ACCENT = "#0b0f14"
ON_NEUTRAL = "#e8edf2"
BRAND = "github.com/alexSerranoR/swarm-search"


def load(name: str) -> dict[str, dict]:
    rows = json.loads((RESULTS / name).read_text())["per_query"]
    return {r["qid"]: r for r in rows}


def mean(xs):
    return sum(xs) / len(xs) if xs else 0.0


def bootstrap_ci(values: list[float], seed: int = SEED) -> tuple[float, float]:
    rng = random.Random(seed)
    n = len(values)
    means = sorted(mean([values[rng.randrange(n)] for _ in range(n)]) for _ in range(BOOTSTRAP))
    return means[int(0.025 * BOOTSTRAP)], means[int(0.975 * BOOTSTRAP) - 1]


def summarize(data: dict[str, dict], qids: list[str]) -> dict:
    rows = [data[q] for q in qids]
    stats = [r.get("stats", {}) for r in rows]
    tin = sum(s.get("input_tokens", 0) for s in stats)
    tout = sum(s.get("output_tokens", 0) for s in stats)
    ndcgs = [r["ndcg@10"] for r in rows]
    return {
        "n": len(rows),
        "ndcg": mean(ndcgs),
        "ndcg_ci": bootstrap_ci(ndcgs),
        "recall": mean([r["recall@10"] for r in rows]),
        "latency": mean([r["latency_s"] for r in rows]),
        "tokens_per_q": (tin + tout) / len(rows),
        "cost_per_q": (tin * PRICE_IN + tout * PRICE_OUT) / 1e6 / len(rows),
        "cost_total": (tin * PRICE_IN + tout * PRICE_OUT) / 1e6,
        "searches": mean([s.get("searches", 0) for s in stats]) if any(stats) else None,
        "messages": mean([s.get("messages", 0) for s in stats]) if any(stats) else None,
        "dup": mean([s["dup_query_rate"] for s in stats]) if all("dup_query_rate" in s for s in stats) else None,
        "padded": mean([s.get("padded", 0) for s in stats]) if any(stats) else None,
    }


def paired(a: dict, b: dict, qids: list[str]) -> dict:
    d = [a[q]["ndcg@10"] - b[q]["ndcg@10"] for q in qids]
    lo, hi = bootstrap_ci(d)
    rng = random.Random(SEED)
    n = len(d)
    boots = [mean([d[rng.randrange(n)] for _ in range(n)]) for _ in range(BOOTSTRAP)]
    return {
        "diff": mean(d), "lo": lo, "hi": hi,
        "p_pos": sum(x > 0 for x in boots) / BOOTSTRAP,
        "wins": sum(x > 1e-9 for x in d), "losses": sum(x < -1e-9 for x in d),
        "ties": sum(abs(x) <= 1e-9 for x in d),
    }


def fmt_ci(lo, hi):
    return f"[{lo:+.3f}, {hi:+.3f}]"


def build():
    FIGS.mkdir(parents=True, exist_ok=True)
    report = ["# Results", "",
              "Generated by `analysis/make_report.py` from `results/*.json`. "
              "All comparisons are paired (same queries). 95% CIs: bootstrap, "
              f"{BOOTSTRAP:,} resamples. Cost uses Claude Haiku 5.5 list prices "
              f"(${PRICE_IN}/M input, ${PRICE_OUT}/M output).", ""]
    summaries = {}

    for exp, cfg in EXPERIMENTS.items():
        data = {m: load(f) for m, f in cfg["files"].items()}
        # the common query set (SciFact: agent/BM25 ran 50 queries, multi-agent 30)
        common = set.intersection(*(set(d) for d in data.values()))
        qids = [q for q in data["bm25"] if q in common]
        summ = {m: summarize(d, qids) for m, d in data.items()}
        summaries[exp] = summ

        report += [f"## {cfg['title']} — {len(qids)} queries", "",
                   "| Method | NDCG@10 | 95% CI | Recall@10 | Latency | Tokens/query | Cost/query | Searches/query | Dup. queries | Messages/query |",
                   "|---|---|---|---|---|---|---|---|---|---|"]
        for m, s in summ.items():
            searches = "—" if s["searches"] is None else f"{s['searches']:.1f}"
            dup = "—" if s["dup"] is None else f"{s['dup'] * 100:.0f}%"
            msgs = "—" if not s["messages"] else f"{s['messages']:.1f}"
            report.append(
                f"| {LABELS[m]} | **{s['ndcg']:.3f}** | [{s['ndcg_ci'][0]:.3f}, {s['ndcg_ci'][1]:.3f}] "
                f"| {s['recall']:.3f} | {s['latency']:.1f} s | {s['tokens_per_q']:,.0f} "
                f"| ${s['cost_per_q']:.4f} | {searches} | {dup} | {msgs} |")
        report += ["", "**Paired comparisons (NDCG@10)**", "",
                   "| Comparison | Δ NDCG@10 | 95% CI | P(Δ > 0) | Wins / ties / losses |",
                   "|---|---|---|---|---|"]
        for a, b in COMPARISONS:
            if a in data and b in data:
                p = paired(data[a], data[b], qids)
                report.append(f"| {LABELS[a]} vs {LABELS[b]} | {p['diff']:+.3f} | {fmt_ci(p['lo'], p['hi'])} "
                              f"| {p['p_pos'] * 100:.0f}% | {p['wins']} / {p['ties']} / {p['losses']} |")
        total = sum(s["cost_total"] for s in summ.values())
        report += ["", f"Total API cost of these runs: **${total:.2f}**", ""]

    # Swarm v1 (no coordination rules) vs v2 on the same 3 SciFact queries
    v1, v2 = load("scifact_swarm_v1_n3.json"), load("scifact_swarm_n3.json")
    q3 = list(v1)
    s1, s2 = summarize(v1, q3), summarize(v2, q3)
    report += ["## Swarm v1 vs v2 (SciFact, 3 queries, qualitative)", "",
               "v1: agents may message but get no coordination rules. "
               "v2: agents must announce their angle in turn 1, share promising IDs, and never repeat a teammate's query.", "",
               "| Version | NDCG@10 | Messages/query | Searches/query | Tokens/query |", "|---|---|---|---|---|",
               f"| v1 | {s1['ndcg']:.3f} | {s1['messages']:.1f} (all sent right before finishing) | {s1['searches']:.1f} | {s1['tokens_per_q']:,.0f} |",
               f"| v2 | {s2['ndcg']:.3f} | {s2['messages']:.1f} (from turn 1) | {s2['searches']:.1f} | {s2['tokens_per_q']:,.0f} |", ""]

    (DOCS / "results.md").write_text("\n".join(report), encoding="utf-8")
    plot_quality_vs_cost(summaries)
    plot_ndcg_ci(summaries)
    plot_coordination(summaries)
    plot_hero(summaries)
    print("Wrote docs/results.md and docs/figures/*.png")


def style(ax):
    ax.set_facecolor(SURFACE)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(MUTED)
        ax.spines[side].set_linewidth(0.8)
    ax.tick_params(colors=INK_2, labelsize=9, length=0)
    ax.grid(True, color=GRID, linewidth=0.8)
    ax.title.set_color(INK)
    ax.set_axisbelow(True)


def sign(fig):
    fig.text(0.995, 0.99, BRAND, ha="right", va="top", fontsize=8, color=INK_2)


def color_for(m):
    return ACCENT if m.startswith("swarm") else NEUTRAL


def plot_quality_vs_cost(summaries):
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.4), facecolor=SURFACE)
    offsets = {"bm25": (8, -4), "agent": (8, -12), "rrf_n": (8, -12), "swarm": (-8, 8), "swarm6": (8, 4)}
    for ax, (exp, summ) in zip(axes, summaries.items()):
        style(ax)
        # BM25 costs $0: draw it at a small positive cost so it fits a log axis, and say so
        floor = 0.0003
        for m, s in summ.items():
            x = max(s["cost_per_q"] * 100, floor)  # cents per query
            ax.scatter(x, s["ndcg"], s=70, color=color_for(m), edgecolor=SURFACE, linewidth=2, zorder=3)
            label = LABELS[m] + (" ($0)" if m == "bm25" else "")
            dx, dy = offsets[m]
            ha = "left" if dx > 0 else "right"
            ax.annotate(label, (x, s["ndcg"]), xytext=(dx, dy), textcoords="offset points",
                        fontsize=9, color=INK, ha=ha)
        ax.set_xscale("log")
        ax.set_xlim(0.0001, 6)
        ax.set_xlabel("Cost per query (US cents, log scale)", color=INK_2, fontsize=9)
        ax.set_ylabel("NDCG@10", color=INK_2, fontsize=9)
        ax.set_title(EXPERIMENTS[exp]["title"], color=INK, fontsize=11, loc="left")
    fig.suptitle("Quality vs. cost: the big jump is BM25 → agent; coordination adds a little",
                 color=INK, fontsize=12, x=0.01, ha="left")
    fig.tight_layout()
    sign(fig)
    fig.savefig(FIGS / "quality_vs_cost.png", dpi=160, facecolor=SURFACE)
    plt.close(fig)


def plot_ndcg_ci(summaries):
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.4), facecolor=SURFACE, sharey=False)
    for ax, (exp, summ) in zip(axes, summaries.items()):
        style(ax)
        ax.grid(axis="x", visible=False)
        methods = list(summ)
        xs = range(len(methods))
        vals = [summ[m]["ndcg"] for m in methods]
        lo = [summ[m]["ndcg"] - summ[m]["ndcg_ci"][0] for m in methods]
        hi = [summ[m]["ndcg_ci"][1] - summ[m]["ndcg"] for m in methods]
        ax.bar(xs, vals, width=0.6, color=[color_for(m) for m in methods], edgecolor=SURFACE, linewidth=2)
        ax.errorbar(xs, vals, yerr=[lo, hi], fmt="none", ecolor=INK, elinewidth=1.2, capsize=4)
        for x, v in zip(xs, vals):
            ax.text(x, v / 2, f"{v:.3f}", ha="center", va="center", fontsize=9,
                    color=ON_ACCENT if methods[x].startswith("swarm") else ON_NEUTRAL, fontweight="bold")
        ax.set_xticks(list(xs), [LABELS[m] for m in methods], fontsize=9, color=INK_2)
        ax.set_ylabel("NDCG@10 (95% bootstrap CI)", color=INK_2, fontsize=9)
        ax.set_title(f"{EXPERIMENTS[exp]['title']}, n={summ['bm25']['n']}", color=INK, fontsize=11, loc="left")
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    sign(fig)
    fig.savefig(FIGS / "ndcg_ci.png", dpi=160, facecolor=SURFACE)
    plt.close(fig)


def plot_coordination(summaries):
    summ = summaries["fiqa"]
    methods = [m for m in ("rrf_n", "swarm", "swarm6") if m in summ]
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.6), facecolor=SURFACE)
    panels = [("dup", "Searches repeating a teammate's exact query", lambda v: f"{v * 100:.0f}%", 100),
              ("tokens_per_q", "Tokens per query", lambda v: f"{v / 1000:.0f}k", 1)]
    for ax, (key, title, fmt, scale) in zip(axes, panels):
        style(ax)
        ax.grid(axis="x", visible=False)
        vals = [summ[m][key] for m in methods]
        xs = range(len(methods))
        ax.bar(xs, [v * scale for v in vals], width=0.55, color=[color_for(m) for m in methods],
               edgecolor=SURFACE, linewidth=2)
        for x, v in zip(xs, vals):
            ax.text(x, v * scale, fmt(v), ha="center", va="bottom", fontsize=9, color=INK)
        ax.set_xticks(list(xs), [LABELS[m] for m in methods], fontsize=9, color=INK_2)
        ax.set_yticks([])
        ax.spines["left"].set_visible(False)
        ax.set_title(title, color=INK, fontsize=11, loc="left")
    fig.suptitle("FiQA: talking halves duplicated work at the same cost; 6 agents duplicate more and cost 2x",
                 color=INK, fontsize=11, x=0.01, ha="left")
    fig.tight_layout()
    sign(fig)
    fig.savefig(FIGS / "coordination.png", dpi=160, facecolor=SURFACE)
    plt.close(fig)


def plot_hero(summaries):
    """16:9 social card (X / LinkedIn): FiQA NDCG@10 per method with CIs."""
    summ = summaries["fiqa"]
    methods = list(summ)
    fig = plt.figure(figsize=(12, 6.75), facecolor=SURFACE)
    fig.text(0.04, 0.895, "Do coordinated agent swarms search better?", fontsize=22, color=INK,
             fontweight="bold", ha="left")
    fig.text(0.04, 0.835, "Replicating the idea of SID-2 Swarm with prompting only (Claude Haiku 5.5, no RL) "
             "· FiQA-2018, 100 queries", fontsize=12, color=INK_2, ha="left")
    ax = fig.add_axes((0.06, 0.14, 0.9, 0.62))
    style(ax)
    ax.grid(axis="x", visible=False)
    xs = range(len(methods))
    vals = [summ[m]["ndcg"] for m in methods]
    lo = [summ[m]["ndcg"] - summ[m]["ndcg_ci"][0] for m in methods]
    hi = [summ[m]["ndcg_ci"][1] - summ[m]["ndcg"] for m in methods]
    ax.bar(xs, vals, width=0.58, color=[color_for(m) for m in methods], edgecolor=SURFACE, linewidth=2)
    ax.errorbar(xs, vals, yerr=[lo, hi], fmt="none", ecolor=INK, elinewidth=1.2, capsize=5)
    for x, m in zip(xs, methods):
        v = summ[m]["ndcg"]
        ax.text(x, v / 2, f"{v:.3f}", ha="center", va="center", fontsize=14, fontweight="bold",
                color=ON_ACCENT if m.startswith("swarm") else ON_NEUTRAL)
        cents = summ[m]["cost_per_q"] * 100
        ax.text(x, -0.045, "free" if cents == 0 else f"{cents:.2f}¢ / query", ha="center", va="top",
                fontsize=10, color=INK_2)
    ax.set_xticks(list(xs), [LABELS[m] for m in methods], fontsize=12, color=INK)
    ax.tick_params(axis="x", pad=6)
    ax.set_ylim(0, 0.46)
    ax.set_ylabel("NDCG@10 (95% bootstrap CI)", color=INK_2, fontsize=10)
    fig.text(0.04, 0.025, "Agent vs BM25: +0.12 (significant)   ·   Swarm vs independent agents + RRF: +0.02 "
             "(P=88%)   ·   6 agents ≈ 3 agents at 2x cost", fontsize=10.5, color=INK, ha="left")
    fig.text(0.96, 0.935, BRAND, fontsize=10, color=ACCENT, ha="right")
    fig.savefig(FIGS / "hero_fiqa.png", dpi=150, facecolor=SURFACE)
    plt.close(fig)


if __name__ == "__main__":
    build()
